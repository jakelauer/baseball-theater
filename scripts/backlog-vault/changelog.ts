/**
 * The changelog's fragments (`changelog.d/<ID>.md`) and the one assembler that turns them
 * into CHANGELOG.md (`pnpm changelog:build`, S156 AC 6).
 *
 * Why fragments: every story used to add its entry to the top of CHANGELOG.md, so any two
 * branches cut from one base conflicted there (owner, 2026-11-20: "The goal is to enable agents
 * to work in tandem on backlog items in a way that they don't conflict"). A `done` story now
 * writes its own file instead, and nothing per story edits CHANGELOG.md: the release rule's
 * step 4 runs the build once per release (CLAUDE.md), and drafts the release's notes from its
 * milestone's fragments.
 *
 * A fragment is Markdown with frontmatter:
 *
 *     ---
 *     effort: <the bold effort header it nests under, or none>
 *     title: <optional: the header of a standalone (`effort: none`) entry>
 *     ---
 *
 *     - **Before, …. Now, ….** … Details: **S<N>** — ….
 *
 * The body is backlog rule 16's entry: the impact-first bullet with its **Details** line. A
 * story with nothing a reader outside the team would call an outcome records its skip in the
 * same place, `skip: <why>` in the frontmatter and no body, so "has a fragment or a recorded
 * skip" is one file to look for ({@link changelogFragmentFor}, which `pnpm backlog:check` calls).
 *
 * CHANGELOG.md as it stood at S156 is kept whole as the history. The build writes one generated
 * block, between {@link BLOCK_START} and {@link BLOCK_END}, just above the history's first
 * `## ` entry header, and replaces only that block on every run, so it is idempotent and never
 * touches a history line. Inside it, entries are newest first (by the commit that added the
 * fragment, or its file time while uncommitted) and grouped by effort: one `## <effort>` header
 * per effort, its entries under it newest first, and the groups in order of their newest entry.
 * A standalone entry gets its own `## <title>` header, and untitled standalone entries share
 * one `## Other changes` group.
 */

import { execFileSync } from "node:child_process";
import {
	existsSync, readdirSync, readFileSync, statSync, writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";
import { parse as parseYaml } from "yaml";

/** The folder of changelog fragments, relative to the repository root. */
export const CHANGELOG_DIR = "changelog.d";
/** The assembled changelog, relative to the repository root. */
export const CHANGELOG = "CHANGELOG.md";
/** First line of the generated block in CHANGELOG.md. */
export const BLOCK_START = "<!-- changelog.d: generated by `pnpm changelog:build` from changelog.d/<ID>.md (newest first); edit the fragments, not this block -->";
/** Last line of the generated block in CHANGELOG.md. */
export const BLOCK_END = "<!-- changelog.d: end of generated block -->";
/** The header untitled standalone entries share. */
export const OTHER_CHANGES = "Other changes";

/** A fragment's file name: a backlog item's ID (a story, a bug or a vault-migration story). */
const FRAGMENT_FILE = /^([SBV]\d+)\.md$/;

/** One parsed `changelog.d/<ID>.md`. */
export interface ChangelogFragment
{
	/** The item it is for (`S156`), from its file name. */
	id: string;
	/** Repository-relative path (`changelog.d/S156.md`). */
	path: string;
	/** The effort header the entry nests under, or `none` for a standalone entry; `none` for a skip. */
	effort: string;
	/** A standalone entry's own header, when it has one. */
	title?: string;
	/** Why the item has no changelog entry, when it records a skip instead of an entry. */
	skip?: string;
	/** The entry's Markdown (the bullet and its Details line); empty for a skip. */
	body: string;
}

/** Thrown for a fragment that isn't in the shape the header comment describes. */
export class ChangelogFragmentError extends Error
{
	override name = "ChangelogFragmentError";
}

/**
 * Parse one fragment's text. `id` is the item it belongs to and `path` names it in errors.
 * Throws {@link ChangelogFragmentError} when the frontmatter is missing or unknown, when an
 * entry has no `effort` or a body that isn't a bullet with a **Details** line, or when a skip
 * also carries an entry.
 */
export function parseChangelogFragment(id: string, text: string, path = `${CHANGELOG_DIR}/${id}.md`): ChangelogFragment
{
	const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(text.replace(/\r\n/g, "\n"));
	if (!m)
	{
		throw new ChangelogFragmentError(`${path}: a changelog fragment starts with frontmatter (--- effort: … ---)`);
	}
	// YAML, as the story notes' frontmatter is (vault.ts writes it with the same library).
	let parsed: unknown;
	try
	{
		parsed = parseYaml(m[1]!);
	}
	catch (error)
	{
		throw new ChangelogFragmentError(`${path}: its frontmatter is not YAML (${(error as Error).message})`);
	}
	const fields: Record<string, string> = {};
	for (const [key, value] of Object.entries(parsed !== null && typeof parsed === "object" ? parsed : {}))
	{
		if (key !== "effort" && key !== "title" && key !== "skip")
		{
			throw new ChangelogFragmentError(`${path}: unknown frontmatter field "${key}" (effort, title and skip are the fields)`);
		}
		fields[key] = value === null || value === undefined ? "" : String(value).trim();
	}
	const body = m[2]!.trim();
	if (fields.skip !== undefined)
	{
		if (fields.skip === "")
		{
			throw new ChangelogFragmentError(`${path}: a skip says why (skip: <reason>)`);
		}
		if (body !== "")
		{
			throw new ChangelogFragmentError(`${path}: a fragment is an entry or a recorded skip, not both`);
		}
		return {
			id,
			path,
			effort: "none",
			skip: fields.skip,
			body: "",
		};
	}
	if (!fields.effort)
	{
		throw new ChangelogFragmentError(`${path}: no effort (the effort header the entry nests under, or none)`);
	}
	if (!/^- /.test(body) || !body.includes("Details"))
	{
		throw new ChangelogFragmentError(`${path}: the body is the entry's bullet ("- **Before, … Now, ….**") with its Details line (backlog rule 16)`);
	}
	return {
		id,
		path,
		effort: fields.effort,
		...(fields.title ? {
			title: fields.title,
		} : {}),
		body,
	};
}

/**
 * The fragment for item `id` under the repository at `root`, or undefined when it has none.
 * This is what `pnpm backlog:check` asks of a story that went `done` after S156: a fragment
 * (an entry or a recorded skip). Throws {@link ChangelogFragmentError} on a malformed one.
 */
export function changelogFragmentFor(root: string, id: string): ChangelogFragment | undefined
{
	const path = `${CHANGELOG_DIR}/${id}.md`;
	const file = join(root, path);
	return existsSync(file) ? parseChangelogFragment(id, readFileSync(file, "utf8"), path) : undefined;
}

/** Every fragment under `root`, by ID. Files that aren't `<ID>.md` (a README) are not fragments. */
export function changelogFragments(root: string): ChangelogFragment[]
{
	const dir = join(root, CHANGELOG_DIR);
	if (!existsSync(dir))
	{
		return [];
	}
	return readdirSync(dir)
		.map((name) => FRAGMENT_FILE.exec(name)?.[1])
		.filter((id): id is string => id !== undefined)
		.sort()
		.map((id) => changelogFragmentFor(root, id)!);
}

/**
 * When each fragment arrived, in seconds: the time of the newest commit that added it (one
 * `git log` over the folder), else, while it is uncommitted or there is no repository, its file
 * time. Newest first in the changelog means newest by this.
 */
export function fragmentTimes(root: string, fragments: ChangelogFragment[]): Map<string, number>
{
	const added = new Map<string, number>();
	try
	{
		const log = execFileSync("git", ["log", "--diff-filter=A", "--name-only", "--format=%x00%ct", "--", `${CHANGELOG_DIR}/`], {
			cwd: root,
			encoding: "utf8",
			maxBuffer: 64 * 1024 * 1024,
			stdio: ["ignore", "pipe", "ignore"],
		});
		// Newest commit first: the first time seen for a path is its newest add.
		for (const commit of log.split("\0").filter(Boolean))
		{
			const [time, ...paths] = commit.split("\n").filter(Boolean);
			for (const path of paths)
			{
				if (!added.has(path))
				{
					added.set(path, Number(time));
				}
			}
		}
	}
	catch
	{
		// Not a repository: every fragment falls back to its file time.
	}
	const times = new Map<string, number>();
	for (const f of fragments)
	{
		times.set(f.id, added.get(f.path) ?? statSync(join(root, f.path)).mtimeMs / 1000);
	}
	return times;
}

/** Remove the generated block (its markers and everything between) from a changelog, if it has one. */
function withoutBlock(lines: string[]): string[]
{
	const start = lines.indexOf(BLOCK_START);
	const end = lines.indexOf(BLOCK_END);
	if (start < 0 || end < start)
	{
		return lines;
	}
	// The block is written with one blank line after it; take that too.
	const after = lines[end + 1] === "" ? end + 2 : end + 1;
	return [...lines.slice(0, start), ...lines.slice(after)];
}

/**
 * CHANGELOG.md assembled from `current` (today's file; its history is every line outside the
 * generated block) and `fragments` with their arrival `times` ({@link fragmentTimes}). Skips
 * have no entry. With no entries, the result is the history alone.
 */
export function renderChangelog(current: string, fragments: ChangelogFragment[], times: Map<string, number>): string
{
	const history = withoutBlock(current.split("\n"));
	const entries = fragments.filter((f) => f.skip === undefined);
	if (entries.length === 0)
	{
		return history.join("\n");
	}
	const time = (f: ChangelogFragment) => times.get(f.id) ?? 0;
	const newestFirst = (a: ChangelogFragment, b: ChangelogFragment) => time(b) - time(a) || itemOrder(b.id, a.id);
	const groups = new Map<string, { header: string;
		entries: ChangelogFragment[]; }>();
	for (const f of entries)
	{
		const [key, header] = f.effort !== "none" ? [`effort:${f.effort}`, f.effort] : f.title ? [`title:${f.id}`, f.title] : ["other", OTHER_CHANGES];
		const group = groups.get(key) ?? {
			header,
			entries: [],
		};
		group.entries.push(f);
		groups.set(key, group);
	}
	const ordered = [...groups.values()].map((g) => ({
		...g,
		entries: g.entries.sort(newestFirst),
	})).sort((a, b) => newestFirst(a.entries[0]!, b.entries[0]!));
	const block = [BLOCK_START, ""];
	for (const g of ordered)
	{
		block.push(`## ${g.header}`, "");
		for (const f of g.entries)
		{
			block.push(...f.body.split("\n"));
		}
		block.push("");
	}
	block.push(BLOCK_END, "");
	const at = history.findIndex((l) => l.startsWith("## "));
	const insertAt = at < 0 ? history.length : at;
	return [...history.slice(0, insertAt), ...block, ...history.slice(insertAt)].join("\n");
}

/** Order item IDs by kind letter, then number (`S9` before `S10`). */
function itemOrder(a: string, b: string): number
{
	return a[0]! === b[0]! ? Number(a.slice(1)) - Number(b.slice(1)) : a < b ? -1 : 1;
}

/** `pnpm changelog:build`: rewrite `root`'s CHANGELOG.md from its history and changelog.d/. */
export function buildChangelog(root: string): void
{
	const fragments = changelogFragments(root);
	const path = join(root, CHANGELOG);
	writeFileSync(path, renderChangelog(readFileSync(path, "utf8"), fragments, fragmentTimes(root, fragments)));
}

if (import.meta.main)
{
	const root = resolve(import.meta.dirname, "../..");
	try
	{
		buildChangelog(root);
		console.log(`changelog: ${CHANGELOG} rebuilt from ${CHANGELOG_DIR}/`);
	}
	catch (error)
	{
		console.error(`changelog: ${(error as Error).message}`);
		process.exit(1);
	}
}
